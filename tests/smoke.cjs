const {chromium}=require('playwright');
(async()=>{
 const browser=await chromium.launch({headless:true});
 try{
  const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8765/',{waitUntil:'load'});
  if((await page.locator('.tabbar button').count())!==4)throw Error('Quatre onglets attendus');
  await page.locator('#tabbtn-calendar').click();
  await page.locator('#monthTitle').waitFor();
  const first=await page.locator('#monthTitle').innerText();
  await page.locator('#monthNext').click();
  const next=await page.locator('#monthTitle').innerText();
  if(first===next)throw Error('Mois suivant ne répond pas');
  await page.locator('#monthPrev').click();
  if((await page.locator('#monthTitle').innerText())!==first)throw Error('Mois précédent ne revient pas');
  await page.locator('#calendar .calcell button').first().click();
  if(!(await page.locator('#calendar .calcell.done').count()))throw Error('Date non cochée');
  await page.locator('#tabbtn-home').click();
  await page.locator('#quickDone').click();
  if(!(await page.locator('#quickDone').innerText()).includes('enregistrée'))throw Error('Activité rapide non enregistrée');
  await page.reload();
  if(!(await page.locator('#quickDone').innerText()).includes('enregistrée'))throw Error('Sauvegarde locale perdue');
  await page.locator('#quickRest').click();
  if(!(await page.locator('#quickRest').innerText()).includes('notée'))throw Error('Repos rapide non enregistré');
  // Régression : enregistrer du foot doit augmenter le compteur sans casser le calendrier.
  await page.locator('#today').click();
  const beforeMinutes=Number((await page.locator('#activeMinutes').innerText()).match(/\d+/)[0]);
  await page.locator('#activityType').selectOption('Foot');
  await page.locator('#activityMinutes').fill('90');
  await page.locator('#activityMode').selectOption('extra');
  await page.locator('#activityForm button[type=submit]').click();
  const afterMinutes=Number((await page.locator('#activeMinutes').innerText()).match(/\d+/)[0]);
  if(afterMinutes-beforeMinutes!==90)throw Error('Foot 90 min non ajouté au compteur');
  if(!(await page.locator('#activityLog').innerText()).includes('Foot · 90 min'))throw Error('Foot absent du journal');
  await page.locator('#tabbtn-calendar').click();
  await page.locator('#monthNext').click();
  await page.locator('#monthPrev').click();
  if((await page.locator('#monthTitle').innerText())!==first)throw Error('Calendrier cassé après ajout foot');
  await page.locator('#tabbtn-home').click();
  await page.reload();
  if(!(await page.locator('#activeMinutes').innerText()).includes(String(afterMinutes)))throw Error('Minutes perdues après rechargement');
  // Les quatre déroulés restent accessibles et réversibles.
  await page.locator('#tabbtn-workout').click();
  const initialSession=await page.locator('#sessionLabel').innerText();
  await page.locator('#sessionNext').click();
  if((await page.locator('#sessionLabel').innerText())===initialSession)throw Error('Navigation séances inactive');
  await page.locator('#sessionPrev').click();
  if((await page.locator('#sessionLabel').innerText())!==initialSession)throw Error('Retour séance impossible');
  await page.locator('#expressPlay').click();
  await page.waitForTimeout(1200);
  await page.locator('#expressPause').click();
  if((await page.locator('#expressClock').innerText())==='10:00')throw Error('Chrono express immobile');
  await page.locator('#expressReset').click();
  if((await page.locator('#expressClock').innerText())!=='10:00')throw Error('Reset chrono express incorrect');
  await page.locator('#coachPlay').click();
  await page.waitForTimeout(1200);
  await page.locator('#coachPause').click();
  if((await page.locator('#coachClock').innerText())==='20:00')throw Error('Chrono 20 min immobile');
  await page.locator('#tabbtn-home').click();
  await page.locator('#today').click();
  const week=await page.locator('#weekLabel').innerText();
  await page.locator('#next').click();
  if((await page.locator('#weekLabel').innerText())===week)throw Error('Semaine suivante immobile');
  await page.locator('#prev').click();
  if((await page.locator('#weekLabel').innerText())!==week)throw Error('Retour semaine incorrect');
  await page.locator('#tabbtn-tracking').click();
  await page.locator('#waist').fill('88.5');
  await page.locator('#measureForm button[type=submit]').click();
  if(!(await page.locator('#lastWaist').innerText()).includes('88,5'))throw Error('Mesure non enregistrée');
  await page.locator('#note').fill('Test de persistance');
  await page.locator('#saveNote').click();
  await page.reload();
  await page.locator('#tabbtn-tracking').click();
  if((await page.locator('#note').inputValue())!=='Test de persistance')throw Error('Note non conservée');
  await page.locator('#printReport').click();
  if(!(await page.locator('#report').innerText()).includes('activité'))throw Error('Bilan non généré');
  await page.locator('#tabbtn-workout').click();
  await page.locator('#coachRestart').click();
  if((await page.locator('#coachClock').innerText())!=='20:00')throw Error('Reset coach incorrect');
  if(errors.length)throw Error('Erreurs navigateur: '+errors.join(' | '));
  console.log('OK : calendriers, boutons, activité, repos, mesures, notes, bilan, persistance, chronos');
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)});
